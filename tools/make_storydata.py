"""Builds mod/PBZCoop/Scripts/storydata.lua: the game's story table, as Phantom Pact's own copy.

The game's update of 2026-11-04 took its QA story tables out of the game (FlowEventTable and FlowQuestBranchStateDataTable
under /Game/PBZContent/Blueprint/FlowGraph/DebugUI/FlowQuest/ no longer load), and with them the story catch-up that applied
their rows. The rows were exported from the game before that (C:/PBZDev/pp-netlab/flowevents.tsv, every column, in the
table's order), and each quest's class path read from a running game (questfolders.tsv). story.lua now applies a row with
the game's own calls: the narrative component's quest branches, the event pipeline's tags and node marks, the bell manager,
the UI visibility manager.

    python -I tools/make_storydata.py [flowevents.tsv] [questfolders.tsv]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "mod", "PBZCoop", "Scripts", "storydata.lua")
FLOW = sys.argv[1] if len(sys.argv) > 1 else r"C:\PBZDev\pp-netlab\flowevents.tsv"
PATHS = sys.argv[2] if len(sys.argv) > 2 else r"C:\PBZDev\pp-netlab\questfolders.tsv"

# Column -> the short key a row keeps it under (only non-empty ones are written).
COLUMNS = {
    "QuestList": "q", "AddTags": "t", "AddGuids": "g", "ActiveBells": "b", "ActiveBellMaps": "m", "ActivateUITags": "u",
}
FINDS = ("AddWeapons", "SnapSoulWeapons", "AddItems", "LootItems")     # a player's own finds: only marked, never given


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = open(FLOW, encoding="utf-8").read().splitlines()
    head = lines[0].split("\t")
    col = {name: head.index(name) for name in list(COLUMNS) + list(FINDS) + ["Optional", "row"]}
    out = ["-- Generated by tools/make_storydata.py from the game's story table as it was before the update of 2026-11-04.",
           "-- Don't edit: run the script again. One row per table row, in the table's order:",
           "-- q quest steps, t tags, g node marks, b bells, m maps whose bells all light, u UI tags,",
           "-- o optional, f hands out things (weapons, items, loot: a player's own finds).",
           "return {", "    rows = {"]
    for line in lines[1:]:
        cells = line.split("\t") + [""] * len(head)
        fields = []
        for name, key in COLUMNS.items():
            v = cells[col[name]].strip()
            if v:
                fields.append("%s = %s" % (key, lua(v)))
        if cells[col["Optional"]].strip() == "True":
            fields.append("o = true")
        if any(cells[col[f]].strip() for f in FINDS):
            fields.append("f = true")
        out.append("        { %s }, -- %s" % (", ".join(fields), cells[col["row"]].replace("\n", " ")))
    out.append("    },")
    out.append("    paths = {")
    for line in open(PATHS, encoding="utf-8").read().splitlines():
        if "\t" in line:
            name, path = line.split("\t", 1)
            out.append("        [%s] = %s," % (lua(name), lua(path.strip())))
    out.append("    },")
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT, len(lines) - 1, "rows")


main()
